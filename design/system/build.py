GLYPH = '<svg viewBox="0 0 16 16" width="{s}" height="{s}" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linecap="round"><path d="M3 8h10M8 3v10"/></svg>'

def specimen(s):
    """One drawn variant of an issue."""
    if not s:
        return ""
    t = s["t"]
    if t == "btn":
        kind = s.get("kind", "outline")
        return (f'<span class="q-btn q-btn-{kind}" style="height:{s["h"]}px;border-radius:{s["r"]}px;'
                f'padding:0 {s.get("px", 14 if kind == "primary" else 12)}px;font-size:{s.get("fs", 13 if kind == "primary" else 12.5)}px">Button</span>')
    if t == "ibtn":
        return f'<span class="q-ibtn is-hover" style="width:{s["box"]}px;height:{s["box"]}px;border-radius:{s["r"]}px">{GLYPH.format(s=s["icon"])}</span>'
    if t == "input":
        return f'<span class="q-input" style="height:{s["h"]}px;border-radius:{s["r"]}px;font-size:{s["fs"]}px;width:150px">Field text</span>'
    if t == "row":
        inset, px = s.get("inset", 8), s.get("px", 8)
        return (f'<span class="q-panel" style="width:170px"><span class="q-row is-current" style="height:{s["h"]}px;font-size:{s["fs"]}px;'
                f'margin:0 {inset}px;padding:0 {px}px">Row text</span></span>')
    if t == "sq":
        return f'<span class="q-sq" style="border-radius:{s["r"]}px"></span>'
    if t == "text":
        return f'<span style="font:400 {s["fs"]}px var(--q-font-ui);color:var(--q-ink)">Quire notes 123</span>'
    if t == "kbd":
        return f'<span class="q-kbd" style="font-size:{s["fs"]}px">Ctrl+K</span>'
    if t == "ring":
        col = "var(--q-mute)" if s.get("faint") else "var(--q-ink)"
        return f'<span class="q-ibtn" style="width:28px;height:28px;border-radius:6px;background:var(--q-hover);outline:{s["w"]}px solid {col};outline-offset:{s["gap"]}px">{GLYPH.format(s=14)}</span>'
    if t == "dis":
        return f'<span class="q-btn q-btn-outline" style="height:32px;border-radius:7px;padding:0 12px;font-size:12.5px;opacity:{s["o"]}">Button</span>'
    if t == "surface":
        sh = {"sh-menu": "sh-popup", "sh-palette": "sh-dialog", "sh-settings": "sh-dialog"}.get(s["sh"], s["sh"])
        return f'<span class="q-surface" style="border-radius:{s["r"]}px;box-shadow:var(--q-{sh})"></span>'
    if t == "bar":
        return (f'<span class="q-minibar" style="padding:0 {s["px"]}px">' + "".join(
            f'<span class="q-ibtn" style="width:24px;height:24px;border-radius:4px">{GLYPH.format(s=12)}</span>' for _ in range(3)) + "</span>")
    if t == "swatch":
        return f'<span class="q-sq" style="background:{s["c"]};border-color:transparent"></span>'
    return ""

def issue_card(i):
    vs = "".join(
        f'<div class="var"><div class="spec">{specimen(v.get("s"))}</div><div class="vl">{E(v["l"])}</div>'
        f'<div class="vv">{E(str(v["v"]))}</div><div class="at">{E(v["at"])}</div></div>' for v in i["variants"])
    why = f'<p class="why"><b>Why it is so.</b> {E(i["why"])}</p>' if i["why"] else ""
    return (f'<article class="issue sev-{i["sev"]}" id="{i["id"]}" data-issue="{i["id"]}" data-area="{E(i["area"])}" data-decision="{E(i.get("decision", ""))}">'
            f'<header><span class="iid">{i["id"]}</span><span class="sev">{i["sev"]}</span><span class="st">{i["status"]}</span><h4>{E(i["title"])}</h4></header>'
            f'<div class="vars">{vs}</div>{why}<p class="prop"><b>Proposal.</b> {E(i["propose"])}</p>'
            f'<p class="decision"><b>Decision:</b> <span class="decision-text">{E(i.get("decision", "")) or "open"}</span></p></article>')

def comp(cid, name, src, body, props):
    rows = "".join(f"<tr><th>{E(k)}</th><td>{E(v)}</td></tr>" for k, v in props)
    panes = "".join(f'<div class="pane t-{t}">{body}</div>' for t in ("paper", "ink"))
    return (f'<article class="comp" id="c-{cid}" data-component="{cid}" data-src="{E(src)}"><header><h4>{E(name)}</h4><code>{E(src)}</code></header>'
            f'<div class="panes">{panes}</div><table class="props">{rows}</table></article>')

