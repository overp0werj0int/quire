def issues_md(issues):
    out = ["# Inconsistencies in Quire's design system", "",
           "Generated by `build.py` from `issues.json`. Paths are under `desktop/src` unless they start with `docs/`, `android` or `design/`.",
           "`checked`: the lines were re-read against the code. `reported`: from a map only, read the lines before acting.", ""]
    area = None
    for i in issues:
        if i["area"] != area:
            area = i["area"]
            out += [f"## {area.capitalize()}", ""]
        out += [f"### {i['id']} · {i['title']}", "", f"Severity {i['sev']}, {i['status']}.", ""]
        out += [f"- {v['l']}: **{v['v']}**" + (f" (`{v['at']}`)" if v["at"] else "") for v in i["variants"]]
        out += [""] + ([f"Why: {i['why']}", ""] if i["why"] else []) + [f"Proposal: {i['propose']}", "", f"Decision: {i.get('decision') or 'open'}", ""]
    return "\n".join(out)

def main():
    themes, accents = read_themes()
    scales = json.loads((HERE / "scales.json").read_text())
    issues = json.loads((HERE / "issues.json").read_text())["issues"]
    tokens = {"source": "desktop/src/theme.rs and design/system/scales.json", "themes": [{k: t[k] for k in ("id", "name", "dark", "colors", "named", "pal", "built")} for t in themes],
              "accents": [{"hex": h, "name": n} for h, n in accents],
              **{g: [{"name": f"--q-{n}", "value": v, "src": s, "note": note} for n, v, s, note in scales[g]] for g in scales if not g.startswith("_")}}
    (HERE / "tokens.json").write_text(json.dumps(tokens, indent=1, ensure_ascii=False) + "\n")
    (HERE / "tokens.css").write_text(css_tokens(themes, scales))
    (HERE / "quire-design-system.html").write_text(page(themes, accents, scales, issues))
    (HERE / "ISSUES.md").write_text(issues_md(issues))
    print(f"{len(themes)} themes, {sum(len(scales[g]) for g in scales if not g.startswith('_'))} scale tokens, {len(issues)} issues")

if __name__ == "__main__":
    main()
