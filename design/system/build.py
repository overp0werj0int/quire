# ---------- colour, as theme.rs computes it ----------

def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))

def dec(v):
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4

def enc(v):
    return 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055

def to_hex(c):
    return "#" + "".join(f"{round(max(0, min(1, v)) * 255):02x}" for v in c)

def mix(a, b, t):
    """Rune's Color::mix: in linear light."""
    return to_hex(tuple(enc(dec(x) + (dec(y) - dec(x)) * t) for x, y in zip(rgb(a), rgb(b))))

def lum(h):
    r, g, b = (dec(v) for v in rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast(a, b):
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + 0.05) / (y + 0.05)

def rgba(h, a):
    r, g, b = (round(v * 255) for v in rgb(h))
    return f"rgba({r},{g},{b},{a:g})"

def readable(c, bg, dark, least):
    toward, out, t = ("#ffffff" if dark else "#000000"), c, 0.0
    while contrast(out, bg) < least and t < 1.0:
        t += 0.05
        out = mix(c, toward, t)
    return out

def scrim(bg, dark):
    return rgba(mix(bg, "#000000", 0.85), 0.6 if dark else 0.4)

def built(t):
    """theme.rs `build` then `with_accent`."""
    bg, side, ink, ink2, mute, mark, acc, err = t["colors"]
    d = t["dark"]
    ha = 0.05 if d else 0.06
    return {
        "desk": side, "bg": bg, "side": side, "ink": ink, "ink2": ink2, "mute": mute, "mark": mark,
        "line": mix(bg, ink, 0.1 if d else 0.11), "hover": rgba(ink, ha), "act": rgba(ink, ha + 0.03),
        "acc": readable(acc, bg, d, 3.0), "soft": mix(bg, acc, 0.2 if d else 0.12), "code": mix(bg, ink, 0.045),
        "err": err, "button": acc, "button-hover": mix(acc, "#000000", 0.14),
        "on-acc": max(("#ffffff", "#000000"), key=lambda c: contrast(c, acc)),
        "sel": rgba(acc, 0.22), "link-line": rgba(acc, 0.4), "scrim": scrim(bg, d),
    }

def read_themes():
    src = THEME_RS.read_text()
    out = []
    for m in re.finditer(r'ThemeDef \{ id: "([^"]+)", name: "([^"]+)", dark: (true|false), colors: \[([^\]]+)\], named: \[([^\]]*)\] \}', src):
        strs = lambda s: re.findall(r'"([^"]*)"', s)
        t = {"id": m[1], "name": m[2], "dark": m[3] == "true", "colors": strs(m[4]), "named": strs(m[5])}
        t["pal"] = built(t)
        t["built"] = True
        out.append(t)
    block = src[src.index("pub const ACCENTS"):]
    accents = re.findall(r'\("(#[0-9a-f]{6})", "([^"]+)"\)', block[:block.index("];")])
    assert len(out) >= 14 and accents, "theme.rs no longer parses: update read_themes"
    return out, accents

