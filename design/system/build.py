UNITLESS = ("motion", "focus", "shadow")

def css_tokens(themes, scales):
    lines = ["/* Quire design tokens, as built. Generated by build.py: edit scales.json or theme.rs, not this file. */", ":root {"]
    lines += ["  --q-font-ui: 'Instrument Sans', system-ui, sans-serif;",
              "  --q-font-panel: 'iA Writer Quattro S', 'IBM Plex Mono', ui-monospace, monospace;",
              "  --q-font-serif: 'Newsreader', Georgia, serif;"]
    for group in ("radius", "size", "space", "type"):
        lines.append(f"  /* {group} */")
        for name, value, src, note in scales[group]:
            lines.append(f"  --q-{name}: {value:g}px; /* {src}: {note} */")
    lines.append("  /* shadow */")
    for name, value, src, note in scales["shadow"]:
        lines.append(f"  --q-{name}: {value}; /* {src}: {note} */")
    lines.append("}")
    for t in themes:
        sel = ":root, .t-paper" if t["id"] == "paper" else f".t-{t['id']}"
        lines.append(f"{sel} {{ /* {t['name']}{', values computed from theme.rs build()' if t['built'] else ''} */")
        lines += [f"  --q-{k}: {v};" for k, v in t["pal"].items()]
        lines.append("}")
    return "\n".join(lines) + "\n"

